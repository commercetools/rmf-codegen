/**
 * Writes one Rust file per RAML package, plus a `mod.rs` that declares them.
 *
 * Shapes:
 * - An object is a struct. A variant (an object with a `discriminatorValue`) owns its tag.
 * - A discriminator base with variants is an enum. It serializes untagged and deserializes by its tag.
 * - A union of variants that share one discriminator is an enum, named after its owner and field when inline.
 * - A string enum is an enum with an `Unknown(String)` case, so a new value does not break decoding.
 * - An object with only pattern properties is a `BTreeMap` alias.
 * - A struct field that closes a containment cycle is boxed.
 */
class RustTypesFileProducer(
    private val vrapTypeProvider: VrapTypeProvider,
    private val packageProvider: PackageProvider,
    private val allAnyTypes: List<AnyType>
) : FileProducer {

    override fun produceFiles(): List<TemplateFile> {
        return RustTypeGenerator(vrapTypeProvider, packageProvider, allAnyTypes).generate()
    }
}

private const val HEADER = "// Code generated by rmf-codegen. DO NOT EDIT."
private const val JSON_VALUE = "serde_json::Value"
private const val BTREE_MAP = "std::collections::BTreeMap"
private const val UNKNOWN = "Unknown"

private enum class RustKind { STRUCT, MAP, UNION, STRING_ENUM, ALIAS }

/** One Rust item the generator writes: where it lives, what it is called and what it is made of. */
private class Entry(val module: String, val name: String, val kind: RustKind, val type: AnyType)

/** The members of a union, with the discriminator they share. */
private class UnionSpec(val tag: String, val variants: List<ObjectType>)

private class RustTypeGenerator(
    private val vrapTypeProvider: VrapTypeProvider,
    private val packageProvider: PackageProvider,
    allAnyTypes: List<AnyType>
) {
    /**
     * The first object seen for each type name. The RAML model can hold more than one object for a type,
     * so every lookup goes by name and returns this object.
     */
    private val firstByName: Map<String, AnyType> = allAnyTypes
        .filter { it.name != null }
        .distinctBy { it.name }
        .associateBy { it.name }

    /** Named RAML types, keyed by name. */
    private val named: Map<String, Entry> = firstByName.values
        .mapNotNull { type ->
            val kind = kindOf(type) ?: return@mapNotNull null
            Entry(moduleNameOf(packageProvider.doSwitch(type)), type.name, kind, type)
        }
        .associateBy { it.name }

    /**
     * The tag field of every variant, keyed by the variant's name. Each tag comes from the union the variant
     * was found under, not from the variant's own discriminator lookup, which gave no tag for `CentPrecisionMoney`.
     */
    private val variantTags: Map<String, String> by lazy {
        val tags = HashMap<String, String>()
        fun tagUnion(union: UnionType) {
            unionSpecOrNull(union)?.let { spec -> spec.variants.forEach { tags.putIfAbsent(it.name, spec.tag) } }
        }
        // Named unions, and the inline unions in struct fields. Read from the owners directly, since
        // `inlineUnions` depends on this map.
        named.values.filter { it.kind == RustKind.UNION }.forEach { entry ->
            val type = entry.type
            if (type is ObjectType) {
                val tag = type.discriminator() ?: return@forEach
                variantsOf(type).forEach { tags.putIfAbsent(it.name, tag) }
            } else if (type is UnionType) {
                tagUnion(type)
            }
        }
        named.values.filter { it.kind == RustKind.STRUCT }.forEach { owner ->
            (owner.type as ObjectType).allProperties.forEach { prop ->
                val type = prop.type
                if (type is UnionType && type.name.isNullOrBlank()) tagUnion(type)
            }
        }
        tags
    }

    /** Inline unions in a struct field, such as `target: ProductReference | ChannelReference`. */
    private val inlineUnions: Map<UnionType, Entry> = collectInlineUnions()

    private val entries: List<Entry> = named.values.toList() + inlineUnions.values

    /** The (module, name) pairs that exist in the output, so a reference to a missing item fails loudly. */
    private val emittedNames: Set<Pair<String, String>> = entries.map { it.module to it.name }.toSet()

    /** Strongly connected components of the struct containment graph, keyed by name. A field inside one is boxed. */
    private val components: Map<String, Int> by lazy { stronglyConnectedComponents() }

    fun generate(): List<TemplateFile> {
        // Two items with one name in one module would be two definitions of one type, which does not compile.
        val duplicates = entries.groupingBy { it.module to it.name }.eachCount().filterValues { it > 1 }.keys
        require(duplicates.isEmpty()) { "more than one Rust item named ${duplicates.joinToString { "${it.second} in ${it.first}" }}" }
        val byModule = entries.groupBy { it.module }.toSortedMap()
        val files = byModule.map { (module, items) ->
            TemplateFile(renderModule(module, items.sortedBy { it.name }), "$module.rs")
        }
        val modDeclarations = byModule.keys.joinToString("\n") { "pub mod $it;" }
        return files + TemplateFile("$HEADER\n\n$modDeclarations\n", "mod.rs")
    }

    // Classification

    private fun kindOf(type: AnyType): RustKind? {
        if (type.name.isNullOrBlank() || type.name == "object") return null
        return when (type) {
            is ObjectType -> when {
                isMap(type) -> RustKind.MAP
                isUnionBase(type) -> RustKind.UNION
                else -> RustKind.STRUCT
            }
            // A union whose members share no discriminator has no output. It is written as JSON, see rustTypeOf.
            is UnionType -> if (unionSpecOrNull(type) != null) RustKind.UNION else null
            is StringType -> if (type.enum.isNotEmpty()) RustKind.STRING_ENUM else RustKind.ALIAS
            else -> RustKind.ALIAS
        }
    }

    private fun collectInlineUnions(): Map<UnionType, Entry> {
        val result = LinkedHashMap<UnionType, Entry>()
        named.values.filter { it.kind == RustKind.STRUCT }.forEach { owner ->
            fieldsOf(owner.type as ObjectType).forEach { prop ->
                val type = prop.type
                if (prop.name != "obj" && type is UnionType && type.name.isNullOrBlank() && unionSpecOrNull(type) != null) {
                    result.getOrPut(type) {
                        Entry(owner.module, owner.name + pascalCase(prop.name), RustKind.UNION, type)
                    }
                }
            }
        }
        return result
    }

    private fun isMap(type: ObjectType): Boolean =
        type.allProperties.isNotEmpty() && type.allProperties.all { it.isPatternProperty() }

    private fun isUnionBase(type: ObjectType): Boolean =
        !type.discriminator().isNullOrEmpty() &&
            type.discriminatorValue.isNullOrEmpty() &&
            variantsOf(type).isNotEmpty()

    /** Every object below the base, at any depth, that has a `discriminatorValue`, once each, by name. */
    private fun variantsOf(base: ObjectType): List<ObjectType> {
        val result = LinkedHashMap<String, ObjectType>()
        val visited = HashSet<String>()
        fun visit(parent: ObjectType) {
            parent.subTypes.forEach { child ->
                if (child is ObjectType && visited.add(child.name)) {
                    if (!child.discriminatorValue.isNullOrEmpty()) result[child.name] = canonical(child)
                    visit(child)
                }
            }
        }
        visit(base)
        return result.values.sortedBy { it.name }
    }

    /** The object the generator keeps for a named type. */
    private fun canonical(type: ObjectType): ObjectType = (firstByName[type.name] as? ObjectType) ?: type

    private fun unionMembers(union: UnionType): List<AnyType> =
        union.oneOf.filter { it !is NilType }

    private fun unionSpec(type: AnyType): UnionSpec = when (type) {
        is ObjectType -> UnionSpec(requireNotNull(type.discriminator()), variantsOf(type))
        is UnionType -> requireNotNull(unionSpecOrNull(type)) { "union '${type.name}' does not share one discriminator" }
        else -> throw unsupported("'${type.name}' is not a union")
    }

    /**
     * The variants of a union whose members are all objects with one shared discriminator.
     * Null for any other union, such as `string | number | Money`, which has no tag to decode by.
     */
    private fun unionSpecOrNull(type: UnionType): UnionSpec? {
        val members = unionMembers(type)
        if (members.size < 2) return null
        val objects = members.map { it as? ObjectType ?: return null }
        val tag = objects.map { it.discriminator() }.distinct().singleOrNull()
        if (tag.isNullOrEmpty() || objects.any { it.discriminatorValue.isNullOrEmpty() }) return null
        return UnionSpec(tag, objects.map { canonical(it) }.sortedBy { it.name })
    }

    /**
     * The field that holds the tag of a variant, such as `action`, or null when the object is not a variant.
     * A `discriminatorValue` without a union to belong to, as on `CloudEventsPayload`, does not make a variant.
     */
    private fun variantTag(type: ObjectType): String? =
        if (type.discriminatorValue.isNullOrEmpty()) null else variantTags[type.name]

    /** The fields of a struct. A variant leaves out its tag, which the serde attribute writes. */
    private fun fieldsOf(type: ObjectType): List<Property> {
        val tag = variantTag(type)
        return type.allProperties.filter { !it.isPatternProperty() && it.name != tag }
    }

    private fun patternPropertyOf(type: ObjectType): Property? {
        val patterns = type.allProperties.filter { it.isPatternProperty() }
        if (patterns.size > 1) throw unsupported("'${type.name}' has more than one pattern property")
        return patterns.singleOrNull()
    }

    /** A union with one member is that member, as in the VrapType provider. */
    private fun unwrap(type: AnyType): AnyType {
        if (type is UnionType) {
            val members = unionMembers(type)
            if (members.size == 1) return unwrap(members.single())
        }
        return type
    }

    /** The struct a field holds directly. A list or a map does not count, since it lives on the heap. */
    private fun directStructTarget(prop: Property): AnyType? {
        if (prop.name == "obj") return null
        val resolved = unwrap(prop.type)
        val target = resolved.name?.let { named[it] }
        return if (target?.kind == RustKind.STRUCT) target.type else null
    }

    private fun stronglyConnectedComponents(): Map<String, Int> {
        val structs = named.values.filter { it.kind == RustKind.STRUCT }
        val graph: Map<String, List<String>> = structs.associate { owner ->
            owner.name to fieldsOf(owner.type as ObjectType).mapNotNull { directStructTarget(it)?.name }
        }
        val index = HashMap<String, Int>()
        val lowLink = HashMap<String, Int>()
        val onStack = HashSet<String>()
        val stack = ArrayDeque<String>()
        val component = HashMap<String, Int>()
        var counter = 0
        var componentCount = 0

        fun connect(node: String) {
            index[node] = counter
            lowLink[node] = counter
            counter++
            stack.addLast(node)
            onStack.add(node)
            for (next in graph[node].orEmpty()) {
                if (!index.containsKey(next)) {
                    connect(next)
                    lowLink[node] = minOf(lowLink.getValue(node), lowLink.getValue(next))
                } else if (next in onStack) {
                    lowLink[node] = minOf(lowLink.getValue(node), index.getValue(next))
                }
            }
            if (lowLink.getValue(node) == index.getValue(node)) {
                while (true) {
                    val member = stack.removeLast()
                    onStack.remove(member)
                    component[member] = componentCount
                    if (member == node) break
                }
                componentCount++
            }
        }

        graph.keys.sorted().forEach { if (!index.containsKey(it)) connect(it) }
        return component
    }

    // Type expressions

    private fun rustTypeOf(type: AnyType, module: String): String {
        val resolved = unwrap(type)
        return when (resolved) {
            is ArrayType -> "Vec<${resolved.items?.let { rustTypeOf(it, module) } ?: JSON_VALUE}>"
            is UnionType -> {
                val entry = inlineUnions[resolved] ?: resolved.name?.let { named[it] }?.takeIf { it.kind == RustKind.UNION }
                when {
                    entry != null -> qualify(entry, module)
                    unionSpecOrNull(resolved) != null -> throw unsupported("a discriminated union in a property that the generator does not name")
                    // Members of different kinds, such as `string | Money`, cannot be told apart by a tag. They stay JSON.
                    else -> JSON_VALUE
                }
            }
            is ObjectType -> {
                if (resolved.name.isNullOrBlank()) {
                    throw unsupported("an inline object in a property; name it in the RAML")
                }
                render(vrapTypeProvider.doSwitch(resolved), module)
            }
            else -> render(vrapTypeProvider.doSwitch(resolved), module)
        }
    }

    private fun render(type: VrapType, module: String): String = when (type) {
        is VrapScalarType -> type.scalarType
        is VrapAnyType -> type.baseType
        is VrapObjectType -> qualify(moduleNameOf(type.`package`), type.simpleClassName, module)
        is VrapEnumType -> qualify(moduleNameOf(type.`package`), type.simpleClassName, module)
        is VrapArrayType -> "Vec<${render(type.itemType, module)}>"
        is VrapNilType -> throw unsupported("a nil type in a property")
    }

    private fun qualify(entry: Entry, module: String): String = qualify(entry.module, entry.name, module)

    private fun qualify(targetModule: String, name: String, module: String): String {
        requireIdent(name, "type")
        if (Pair(targetModule, name) !in emittedNames) {
            throw unsupported("'$name' is referenced but the generator does not write it")
        }
        return if (targetModule == module) name else "super::$targetModule::$name"
    }

    // Rendering

    private fun renderModule(module: String, items: List<Entry>): String {
        val kindsHere = items.map { it.kind }.toSet()
        val blocks = items.map { renderEntry(it, module) }

        val imports = mutableListOf<String>()
        if (kindsHere.any { it == RustKind.STRUCT || it == RustKind.UNION || it == RustKind.STRING_ENUM }) {
            val serde = mutableListOf("Deserialize")
            if (RustKind.UNION in kindsHere || RustKind.STRING_ENUM in kindsHere) serde.add("Deserializer")
            serde.add("Serialize")
            if (RustKind.STRING_ENUM in kindsHere) serde.add("Serializer")
            imports.add("use serde::{${serde.joinToString(", ")}};")
        }
        if (RustKind.UNION in kindsHere) imports.add("use serde::de::Error as _;")

        val head = listOf(HEADER) + if (imports.isEmpty()) emptyList() else listOf(imports.joinToString("\n"))
        return (head + blocks).joinToString("\n\n") + "\n"
    }

    private fun renderEntry(entry: Entry, module: String): String = when (entry.kind) {
        RustKind.STRUCT -> renderStruct(entry, module)
        RustKind.MAP -> renderMap(entry, module)
        RustKind.UNION -> renderUnion(entry, module)
        RustKind.STRING_ENUM -> renderStringEnum(entry)
        RustKind.ALIAS -> "pub type ${requireIdent(entry.name, "type")} = ${rustTypeOf(entry.type, module)};"
    }

    private fun renderStruct(entry: Entry, module: String): String {
        val type = entry.type as ObjectType
        val name = requireIdent(entry.name, "type")
        val fields = fieldsOf(type)
        val names = fields.map { snakeCase(it.name).rustIdent() }
        require(names.toSet().size == names.size) { "'$name' has two fields that map to the same Rust name" }

        val pattern = patternPropertyOf(type)
        val tag = variantTag(type)
        val body = mutableListOf<String>()
        // A flattened map would also take a variant's tag key, and the tag attribute would then write it twice.
        // A declared field that is read but never written keeps the key out of the map. The tag attribute writes it.
        if (tag != null && pattern != null) {
            body.add("    #[serde(rename = \"${tag.escapeRust()}\", skip_serializing)]\n    pub ${snakeCase(tag).rustIdent()}: Option<String>,")
        }
        body.addAll(fields.map { renderField(entry, it, module) })
        // An object with no declared properties is open, such as the parent `SearchQuery`. Its unknown keys
        // are kept in `extra`, so a subtype's fields are not dropped. A variant is not open: its tag is not extra.
        val extraType = when {
            pattern != null -> rustTypeOf(pattern.type, module)
            fields.isEmpty() && tag == null -> JSON_VALUE
            else -> null
        }
        if (extraType != null) {
            body.add("    #[serde(flatten)]\n    pub extra: $BTREE_MAP<String, $extraType>,")
        }

        val hasOptional = fields.any { it.name == "obj" || !it.required } || (tag != null && pattern != null)
        val attributes = mutableListOf<String>()
        if (hasOptional) attributes.add("#[serde_with::skip_serializing_none]")
        attributes.add("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]")
        attributes.add("#[serde(rename_all = \"camelCase\")]")
        tag?.let {
            attributes.add("#[serde(tag = \"${it.escapeRust()}\", rename = \"${type.discriminatorValue.escapeRust()}\")]")
        }
        attributes.add("#[non_exhaustive]")

        val fieldBlock = if (body.isEmpty()) "" else "\n" + body.joinToString("\n") + "\n"
        return attributes.joinToString("\n") + "\npub struct $name {$fieldBlock}"
    }

    private fun renderField(owner: Entry, prop: Property, module: String): String {
        val rustName = snakeCase(prop.name).rustIdent()
        requireIdent(rustName, "field of '${owner.name}'")

        val isOpaque = prop.name == "obj"
        var inner = if (isOpaque) JSON_VALUE else rustTypeOf(prop.type, module)
        val target = directStructTarget(prop)
        if (target != null && components[owner.name] == components[target.name]) {
            inner = "Box<$inner>"
        }
        val type = if (isOpaque || !prop.required) "Option<$inner>" else inner

        // serde's rename_all covers the plain cases. A keyword suffix, or a name camelCase cannot rebuild, needs an explicit rename.
        val needsRename = rustName.endsWith("_") || camelCase(rustName) != prop.name
        val rename = if (needsRename) "    #[serde(rename = \"${prop.name.escapeRust()}\")]\n" else ""
        return "$rename    pub $rustName: $type,"
    }

    private fun renderMap(entry: Entry, module: String): String {
        val type = entry.type as ObjectType
        val pattern = requireNotNull(patternPropertyOf(type)) { "'${type.name}' is a map without a pattern property" }
        return "pub type ${requireIdent(entry.name, "type")} = $BTREE_MAP<String, ${rustTypeOf(pattern.type, module)}>;"
    }

    private fun renderUnion(entry: Entry, module: String): String {
        val name = requireIdent(entry.name, "type")
        val spec = unionSpec(entry.type)
        val variantNames = spec.variants.map { pascalCase(it.discriminatorValue) }
        require(variantNames.toSet().size == variantNames.size) {
            val described = spec.variants.zip(variantNames).joinToString { (variant, variantName) ->
                "${variant.name} (${variant.discriminatorValue} -> $variantName)"
            }
            "union '$name' has two variants with the same Rust name: $described"
        }
        require(UNKNOWN !in variantNames) { "union '$name' has a variant named '$UNKNOWN', which the generator reserves" }

        val variantTypes = spec.variants.map { qualify(moduleNameOf(packageProvider.doSwitch(it)), it.name, module) }
        val variantLines = variantNames.zip(variantTypes).joinToString("\n") { (variantName, variantType) ->
            "    $variantName(Box<$variantType>),"
        }
        val fromImpls = variantNames.zip(variantTypes).joinToString("\n\n") { (variantName, variantType) ->
            """
            |impl From<$variantType> for $name {
            |    fn from(value: $variantType) -> Self {
            |        Self::$variantName(Box::new(value))
            |    }
            |}
            """.trimMargin()
        }
        val matchArms = spec.variants.zip(variantNames).zip(variantTypes).joinToString("\n") { (pair, variantType) ->
            val (variant, variantName) = pair
            "            \"${variant.discriminatorValue.escapeRust()}\" => serde_json::from_value::<$variantType>(value)\n" +
                "                .map(|variant| Self::$variantName(Box::new(variant)))\n" +
                "                .map_err(D::Error::custom),"
        }
        val tag = spec.tag.escapeRust()

        return """
            |#[derive(Debug, Clone, PartialEq, Serialize)]
            |#[serde(untagged)]
            |#[non_exhaustive]
            |pub enum $name {
            |$variantLines
            |    $UNKNOWN($JSON_VALUE),
            |}
            |
            |impl<'de> Deserialize<'de> for $name {
            |    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> std::result::Result<Self, D::Error> {
            |        let value = $JSON_VALUE::deserialize(deserializer)?;
            |        let tag = value
            |            .get("$tag")
            |            .and_then($JSON_VALUE::as_str)
            |            .map(str::to_owned)
            |            .ok_or_else(|| D::Error::missing_field("$tag"))?;
            |        match tag.as_str() {
            |$matchArms
            |            _ => Ok(Self::$UNKNOWN(value)),
            |        }
            |    }
            |}
            |
            |$fromImpls
            """.trimMargin()
    }

    private fun renderStringEnum(entry: Entry): String {
        val type = entry.type as StringType
        val name = requireIdent(entry.name, "type")
        val values = type.enum.filterIsInstance<StringInstance>().mapNotNull { it.value }
        val variants = values.map { pascalCase(it) to it }
        require(variants.map { it.first }.toSet().size == variants.size) {
            "enum '$name' has two values with the same Rust name"
        }
        require(variants.none { it.first == UNKNOWN }) { "enum '$name' has a value named '$UNKNOWN', which the generator reserves" }

        val variantLines = variants.joinToString("\n") { "    ${it.first}," }
        val asStrArms = variants.joinToString("\n") { "            Self::${it.first} => \"${it.second.escapeRust()}\"," }
        val fromArms = variants.joinToString("\n") { "            \"${it.second.escapeRust()}\" => Self::${it.first}," }

        return """
            |#[derive(Debug, Clone, PartialEq, Eq)]
            |#[non_exhaustive]
            |pub enum $name {
            |$variantLines
            |    $UNKNOWN(String),
            |}
            |
            |impl $name {
            |    pub fn as_str(&self) -> &str {
            |        match self {
            |$asStrArms
            |            Self::$UNKNOWN(value) => value.as_str(),
            |        }
            |    }
            |}
            |
            |impl Serialize for $name {
            |    fn serialize<S: Serializer>(&self, serializer: S) -> std::result::Result<S::Ok, S::Error> {
            |        serializer.serialize_str(self.as_str())
            |    }
            |}
            |
            |impl<'de> Deserialize<'de> for $name {
            |    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> std::result::Result<Self, D::Error> {
            |        let value = String::deserialize(deserializer)?;
            |        Ok(match value.as_str() {
            |$fromArms
            |            _ => Self::$UNKNOWN(value),
            |        })
            |    }
            |}
            """.trimMargin()
    }

    private fun unsupported(reason: String): IllegalArgumentException =
        IllegalArgumentException("Rust types generator does not support this: $reason")
}
